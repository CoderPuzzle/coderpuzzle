SELECT
  CASE CAST(STRFTIME('%w', day) AS INTEGER)
    WHEN 0 THEN 'Sunday'
    WHEN 1 THEN 'Monday'
    WHEN 2 THEN 'Tuesday'
    WHEN 3 THEN 'Wednesday'
    WHEN 4 THEN 'Thursday'
    WHEN 5 THEN 'Friday'
    ELSE 'Saturday'
  END || ', ' || CASE CAST(STRFTIME('%m', day) AS INTEGER)
    WHEN 1 THEN 'January'
    WHEN 2 THEN 'February'
    WHEN 3 THEN 'March'
    WHEN 4 THEN 'April'
    WHEN 5 THEN 'May'
    WHEN 6 THEN 'June'
    WHEN 7 THEN 'July'
    WHEN 8 THEN 'August'
    WHEN 9 THEN 'September'
    WHEN 10 THEN 'October'
    WHEN 11 THEN 'November'
    ELSE 'December'
  END || ' ' || CAST(CAST(STRFTIME('%d', day) AS INTEGER) AS TEXT) || ', ' || STRFTIME('%Y', day) AS day
FROM
  Days